# ------------------------- Задача 14 --------------------------------
heading(14, "Broadcasting: нормировка признаков и попарные расстояния")

rng14 = np.random.default_rng(1)
X14 = rng14.normal(size=(100, 3))

X_norm = (X14 - X14.mean(axis=0)) / X14.std(axis=0)
print("X shape:", X14.shape, "-> X_norm shape:", X_norm.shape)
print("X_norm.mean(axis=0) ≈ 0 :", np.round(X_norm.mean(axis=0), 12))
print("X_norm.std(axis=0)  ≈ 1 :", np.round(X_norm.std(axis=0), 12))

# D[i, j] = ||X_norm[i] - X_norm[j]|| — одна строка, без цикла:
diff = X_norm[:, None, :] - X_norm[None, :, :]
D14 = np.sqrt((diff ** 2).sum(axis=-1))

print("\nD.shape =", D14.shape)
print("Диагональ max |D[i,i]| =", np.abs(np.diag(D14)).max(), " (≈ 0)")
print("Симметричность max |D - D.T| =", np.abs(D14 - D14.T).max(), " (≈ 0)")
print("Углы D (первые 4x4):\n", np.round(D14[:4, :4], 3))

print("""
ВЫВОД: broadcasting нормирует столбцы одной строкой: (100,3) минус (3,)
и делённое на (3,) — среднее и std 'растягиваются' на все строки.
Расстояния считаются через newaxis: X[:, None, :] даёт форму (100,1,3),
X[None, :, :] — (1,100,3); разность broadcast в (100,100,3), а свёртка
по последней оси — евклидова норма для каждой пары. Всё без циклов.
Память под (100,100,3) мала; на больших N выгоднее формула через a@a
(квадраты расстояний), но для наглядности здесь прямой вариант.""")

