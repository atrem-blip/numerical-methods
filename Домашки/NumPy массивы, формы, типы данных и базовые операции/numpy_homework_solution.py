clean[mask_out] = np.nan
col_mean = np.nanmean(clean, axis=0)
clean = np.where(np.isnan(clean), col_mean, clean)   # broadcasting (30,4) vs (4,)
print("3) NaN заменены на средние по столбцам:", np.round(col_mean, 3))

# 4. Транспонирование туда-обратно
transposed = clean.T          # (4, 30)
back = transposed.T           # (30, 4)
print("4) после .T и обратно .T данные не изменились:",
      np.array_equal(clean, back), " shape:", transposed.shape, "->", back.shape)

# 5. ravel и reshape
flat = clean.ravel()          # (120,)
restored = flat.reshape(30, 4)
print("5) ravel ->", flat.shape, ", reshape обратно ->", restored.shape,
      ", равенство:", np.array_equal(clean, restored))

# 6. Агрегации по датчикам (axis=0)
means6 = clean.mean(axis=0)
stds6 = clean.std(axis=0)
print("6) средние по датчикам:", np.round(means6, 3))
print("   std по датчикам    :", np.round(stds6, 3))

# 7. Нормировка столбцов через broadcasting
Z15 = (clean - means6) / stds6
print("7) Z.mean(axis=0) ≈ 0 :", np.round(Z15.mean(axis=0), 12))
print("   Z.std(axis=0)  ≈ 1 :", np.round(Z15.std(axis=0), 12))

