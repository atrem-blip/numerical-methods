import math
import mpmath
import matplotlib
matplotlib.use("Agg")
import matplotlib.pyplot as plt

mpmath.mp.dps = 50  # 50 значащих цифр для эталона

def rel_err(approx, ref):
    """Относительная погрешность |approx - ref| / |ref|."""
    if approx == ref:
        return 0.0
    return abs((mpmath.mpf(approx) - mpmath.mpf(ref)) / mpmath.mpf(ref))


# ---------------------------------------------------------------
# Задача 5. Квадратное уравнение: x^2 + b*x + 1 = 0 (a = c = 1)
# Плохо:  x2 = (-b + sqrt(b^2 - 4ac)) / (2a)
# Хорошо: x2 = 2c / (-b - sqrt(b^2 - 4ac))
# (обе формулы дают один и тот же корень - меньший по модулю)
# ---------------------------------------------------------------
print("=" * 74)
print("ЗАДАЧА 5. Квадратное уравнение x^2 + b*x + 1 = 0, a = c = 1")
print("=" * 74)
print(f"{'b':>16} | {'эталон x2':>25} | {'ошибка плохого':>14} | {'ошибка хорошего':>15}")
print("-" * 74)

task5 = []
for b in (1e8, 1e4, 1e12):
    disc = mpmath.sqrt(mpmath.mpf(b) ** 2 - 4)          # эталонный дискриминант
    ref = (-mpmath.mpf(b) + disc) / 2                   # эталонный корень

    bad = (-b + math.sqrt(b * b - 4)) / 2               # плохо
    good = 2 / (-b - math.sqrt(b * b - 4))              # хорошо

    e_bad, e_good = rel_err(bad, ref), rel_err(good, ref)
    task5.append((b, e_bad, e_good))
    print(f"{b:>16.0e} | {mpmath.nstr(ref, 12):>25} | {mpmath.nstr(e_bad, 4):>14} | {mpmath.nstr(e_good, 4):>15}")

print("\nВЫВОД: 'плохой' способ катастрофически ошибается, когда b^2 >> 4ac:")
print("  дискриминант b^2 - 4 вычисляется вычитанием почти равных чисел и")
print("  все младшие разряды теряются. Уже при b = 10^4 ошибка ~1e-8,")
print("  при b = 10^8 она достигает 1e-8..1e-9 (предел точности double для"),
print("  корня ~1e-8), а при b = 10^12 результат полностью мусорный.")
print("  'Хороший' способ устойчив при любом b.\n")


# ---------------------------------------------------------------
# Задача 6. f(x) = (1 - cos x) / x^2 при малых x
# Плохо:  в лоб (1 - cos x) / x^2
# Хорошо: 2*sin(x/2)^2 / x^2
# ---------------------------------------------------------------
print("=" * 74)
print("ЗАДАЧА 6. f(x) = (1 - cos x) / x^2 при малых x")
print("=" * 74)
print(f"{'x':>10} | {'эталон':>22} | {'ошибка плохого':>14} | {'ошибка хорошего':>15}")
print("-" * 74)

xs6 = [1e-2, 1e-4, 1e-6, 1e-8, 1e-10]
task6 = []
for x in xs6:
    ref = (1 - mpmath.cos(mpmath.mpf(x))) / mpmath.mpf(x) ** 2

    bad = (1.0 - math.cos(x)) / x**2      # плохо
    good = 2.0 * math.sin(x / 2)**2 / x**2  # хорошо

    e_bad, e_good = rel_err(bad, ref), rel_err(good, ref)
    task6.append((x, e_bad, e_good))
    print(f"{x:>10.0e} | {mpmath.nstr(ref, 12):>22} | {mpmath.nstr(e_bad, 4):>14} | {mpmath.nstr(e_good, 4):>15}")

# При каком x ошибка плохого способа превышает 1%?
first_1pct = next((x for x, e_bad, _ in task6 if e_bad > 1e-2), None)
print(f"\nОшибка 'плохого' способа впервые превышает 1% при x = {first_1pct:.0e}")

# Log-log график
bx = [x for x, _, _ in task6]
