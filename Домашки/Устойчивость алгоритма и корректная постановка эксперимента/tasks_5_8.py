eg = [float(e) for _, _, e in task6]
plt.figure(figsize=(7, 5))
plt.loglog(bx, eb, "o-", label="'плохо': (1 - cos x)/x^2")
plt.loglog(bx, eg, "s--", label="'хорошо': 2 sin^2(x/2)/x^2")
plt.axhline(1e-2, color="gray", ls=":", lw=1, label="уровень 1%")
plt.xlabel("x (log)")
plt.ylabel("относительная ошибка (log)")
plt.title("Задача 6: погрешность вычисления (1 - cos x)/x^2")
plt.grid(True, which="both", alpha=0.3)
plt.legend()
plt.tight_layout()
plt.savefig("task6_loglog.png", dpi=150)

print("\nВЫВОД: пока 1 - cos x не теряет значащих цифр, всё хорошо. Порог ~x < 1e-4:")
print("  1 - cos x ~ x^2/2 ~ 1e-8, а относительная ошибка double ~1e-16, поэтому")
print("  ошибка результата скачком растёт как eps/x^2. Начиная с x = 1e-6 ошибка")
print("  уже > 1%, при x = 1e-10 'плохой' способ даёт 100% мусор (и даже знак 0).")
print("  ПРАВИЛО: как только в формуле появляется вычитание близких чисел")
print("  (1 - cos x, f(x) - f(x0) и т.п.), ищите тождество, устраняющее вычитание.\n")


