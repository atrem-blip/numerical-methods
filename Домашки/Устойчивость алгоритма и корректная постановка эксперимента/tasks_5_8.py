# Задача 7. sqrt(x+1) - sqrt(x) при больших x
# Плохо:  sqrt(x+1) - sqrt(x)
# Хорошо: 1 / (sqrt(x+1) + sqrt(x))
# ---------------------------------------------------------------
print("=" * 74)
print("ЗАДАЧА 7. sqrt(x+1) - sqrt(x) при больших x")
print("=" * 74)
print(f"{'x':>10} | {'эталон':>25} | {'ошибка плохого':>14} | {'ошибка хорошего':>15}")
print("-" * 74)

xs7 = [1e4, 1e8, 1e12, 1e14, 1e16]
task7 = []
for x in xs7:
    X = mpmath.mpf(x)
    ref = mpmath.sqrt(X + 1) - mpmath.sqrt(X)

    bad = math.sqrt(x + 1) - math.sqrt(x)   # плохо
    good = 1 / (math.sqrt(x + 1) + math.sqrt(x))  # хорошо

    e_bad, e_good = rel_err(bad, ref), rel_err(good, ref)
    task7.append((x, e_bad, e_good))
    print(f"{x:>10.0e} | {mpmath.nstr(ref, 14):>25} | {mpmath.nstr(e_bad, 4):>14} | {mpmath.nstr(e_good, 4):>15}")

# Оценка показателя степени роста ошибки: log10(err) ~ k * log10(x) + C
import numpy as np
lx = np.log10(xs7)
le = np.log10([max(float(e), 1e-20) for _, e, _ in task7])
k, c = np.polyfit(lx, le, 1)
print(f"\nОценка показателя степени роста ошибки плохого способа: k = {k:.2f}")
print("(ошибка растёт примерно как x^k)")

print("\nВЫВОД: разность sqrt(x+1) - sqrt(x) ~ 1/(2 sqrt(x)) убывает как x^-1/2,")
print("  при этом её абсолютная ошибка остаётся ~ eps*sqrt(x) ~ 1e-16*sqrt(x).")
print("  Относительная ошибка растёт как eps * x, т.е. показатель k = 1:")
print("  каждый +2 порядка в x дают +2 порядка ошибки. При x = 1e16 результат")
print("  'плохого' способа теряет точность полностью (ошибка ~ 1 или больше).")
print("  Рационализация 1/(sqrt(x+1)+sqrt(x)) устойчива при любом x.\n")


