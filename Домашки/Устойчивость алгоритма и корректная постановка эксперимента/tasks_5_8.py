# Задача 8. ln(1 + x) при малых x: math.log(1+x) vs math.log1p(x)
# ---------------------------------------------------------------
print("=" * 74)
print("ЗАДАЧА 8. ln(1 + x) при малых x: log(1+x) против log1p(x)")
print("=" * 74)
print(f"{'x':>10} | {'эталон ln(1+x)':>24} | {'ошибка log(1+x)':>15} | {'ошибка log1p(x)':>15}")
print("-" * 74)

xs8 = [1e-2, 1e-8, 1e-12, 1e-16]
for x in xs8:
    ref = mpmath.log(1 + mpmath.mpf(x))
    bad = math.log(1 + x)    # плохо: 1 + x уже округлён до 1
    good = math.log1p(x)     # хорошо

    e_bad, e_good = rel_err(bad, ref), rel_err(good, ref)
    print(f"{x:>10.0e} | {mpmath.nstr(ref, 12):>24} | {mpmath.nstr(e_bad, 4):>15} | {mpmath.nstr(e_good, 4):>15}")

print("""
ЧТО ДЕЛАЕТ log1p ВНУТРИ
  В CPython math.log1p - обёртка над C-функцией log1p из libc (стандарт C99).
  Она вычисляет ln(1 + x), НЕ складывая 1 и x в double: алгоритм использует
  разложение вокруг нуля (полиномиальная аппроксимация ln(1+u), u = x,
  с дополнительными членами коррекции k*log(2), когда аргумент приведён),
  поэтому ни одна значащая цифра маленького x не теряется при сложении.
  В отличие от этого при x = 1e-16 сумма 1 + x в double округляется ровно
  до 1.0, и log(1.0) = 0 - результат отличается от эталона на 100%.

ПОЧЕМУ ЭТО ВАЖНО И ЗАЧЕМ НУЖНЫ log1p, expm1, hypot
  Общий принцип: стандартная библиотека даёт функции для "опасных" операций,
  где наивная запись теряет точность из-за округления промежуточного
  результата:
    log1p(x)   = ln(1 + x)  при |x| << 1  (сложение с 1 съедает младшие
               разряды x)
    expm1(x)   = e^x - 1    при |x| << 1  (вычитание почти равных чисел,
               аналогично задаче 7)
    hypot(a,b) = sqrt(a^2 + b^2)  без переполнения/потери точности, когда
               a^2 или b^2 выходят за диапазон double
  Правило то же, что в задачах 5-7: если формула содержит сложение 1 + eps,
  вычитание близких величин или сумму квадратов больших чисел - ищите
  готовую устойчивую функцию, прежде чем писать формулу "в лоб".
""")


