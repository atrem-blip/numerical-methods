print("Задача 8. Округление и banker's rounding")
print("=" * 60)

vals = [0.5, 1.5, 2.5, 3.5, -0.5, -1.5, -2.5]
print("print(round(0.5), round(1.5), round(2.5), round(3.5),")
print("      round(-0.5), round(-1.5), round(-2.5))")
print("=>", [round(v) for v in vals])
print("Python округляет к ближайшему ЧЁТНОМУ (banker's rounding, IEEE 754):")
print("0.5 -> 0, 2.5 -> 2, но 1.5 -> 2, 3.5 -> 4 — не 'всегда вверх'.")

random.seed(42)
arr = [random.randint(0, 9) + 0.5 for _ in range(1_000_000)]

true_sum = sum(arr)                       # сумма точных значений k+0.5
sum_up   = sum(int(v + 0.5) for v in arr)          # округление всегда вверх
sum_bank = sum(round(v) for v in arr)              # banker's rounding

print()
print("Массив из 10^6 чисел вида k+0.5, k = 0..9:")
print(f"Точная сумма:              {true_sum:.0f}")
print(f"Сумма с округлением вверх: {sum_up:.0f}  (сдвиг +{sum_up - true_sum:.0f})")
print(f"Сумма с banker's rounding: {sum_bank:.0f}  (сдвиг {sum_bank - true_sum:+.0f})")
print(f"Систематический сдвиг 'вверх' против banker's: {sum_up - sum_bank:+.0f}")
print("Объяснение: для чётных k (0.5, 2.5, ...) banker's округляет ВНИЗ, а 'вверх' —")
print("всегда вверх: разница ровно 1 на каждое такое число; для нечётных k оба способа")
print("совпадают. При равномерном k это в среднем +0.5 сдвига на каждое число.")
print("Вывод: в финансах такой сдвиг — сотни тысяч рублей на миллионе операций;")
print("именно поэтому используют banker's rounding или целочисленный учёт в копейках.")
