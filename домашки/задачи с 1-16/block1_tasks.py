# Блок 1. Абсолютная и относительная погрешность (задачи 1–4)
# ============================================================
import math

# ---------- Задача 1. Ручной счёт ----------
pairs = [
    ("1) x = 3.14,  x* = pi",  3.14,  math.pi),
    ("2) x = 2.718, x* = e",   2.718, math.e),
    ("3) x = 9.8,   x* = 9.81", 9.8,  9.81),
    ("4) x = 0.333, x* = 1/3", 0.333, 1/3),
]

print("=" * 60)
print("Задача 1. Ручной счёт")
print("=" * 60)

results = []
for name, approx, exact in pairs:
    dx = abs(approx - exact)              # абсолютная погрешность
    dx_rel = dx / abs(exact) * 100        # относительная погрешность, %
    results.append((name, approx, exact, dx, dx_rel))
    print(f"{name}:  Δx = {dx:.6f},  δx = {dx_rel:.3f}%")

order_abs = sorted(results, key=lambda r: r[3])
order_rel = sorted(results, key=lambda r: r[4])

print("\nПорядок по Δx  (лучший → худший):",
      " -> ".join(r[0].split(')')[0] for r in order_abs))
print("Порядок по δx  (лучший → худший):",
      " -> ".join(r[0].split(')')[0] for r in order_rel))

print("""
Вывод: порядок по Δx и по δx НЕ совпадает (у пары 0.333 и 1/3
абсолютная ошибка наименьшая из «плохих», но точное значение само
мало — 1/3, поэтому относительная ошибка велика, ~0.1%).
«Качество» приближения корректнее сравнивать по относительной
погрешности: она безразмерна и учитывает масштаб величины.
""")

# ---------- Задача 2. Сравнение несопоставимых величин ----------
print("=" * 60)
print("Задача 2. Сравнение несопоставимых величин")
print("=" * 60)

for label, approx, exact, unit in [("Мост", 1247, 1250, "м"),
                                   ("Болт", 9.7, 10.0, "мм")]:
    dx = abs(approx - exact)
    dx_rel = dx / exact * 100
    print(f"{label}: Δx = {dx:.1f} {unit},  δx = {dx_rel:.2f}%")

print("""
Вывод: по абсолютной погрешности «сильнее» ошибся мост (3 м против
0.3 мм), но по относительной — болт (3% против 0.24%). Абсолютные
погрешности разных величин несопоставимы: единицы измерения и
масштабы различаются. Относительная погрешность показывает долю
ошибки и именно она отвечает на вопрос, кто ошибся «сильнее».
""")

# ---------- Задача 3. Функция relative_error ----------
print("=" * 60)
print("Задача 3. Функция relative_error")
print("=" * 60)

def relative_error(approx, exact):
    """Относительная погрешность; при exact == 0 возвращает inf."""
    if exact == 0:
        return float('inf')
    return abs(approx - exact) / abs(exact)

for name, approx, exact, _, _ in results:
    print(f"{name}: relative_error = {relative_error(approx, exact):.6f} "
          f"({relative_error(approx, exact) * 100:.3f}%)")

print("Защита от деления на ноль: relative_error(5, 0) =",
      relative_error(5, 0))
print("""
Вывод: функция даёт те же значения, что и ручной счёт в задаче 1,
и не падает с ZeroDivisionError при exact == 0 — возвращает inf.
""")

# ---------- Задача 4. Обратная задача ----------
print("=" * 60)
print("Задача 4. Обратная задача — оценка точного значения")
print("=" * 60)

x = 47.3
delta_rel = 0.001           # 0.1%
dx = x * delta_rel          # абсолютная погрешность
a, b = x - dx, x + dx
print(f"Δx = x * δ = {x} * {delta_rel} = {dx:.4f}")
print(f"x* ∈ [{a:.4f}, {b:.4f}]")
print(f"С разумным числом значащих цифр: x* ∈ [{a:.2f}, {b:.2f}]")
print("""
Вывод: относительной погрешности 0.1% соответствует абсолютная
~0.05, поэтому верны только разряды десятых и сотых:
x* ∈ [47.25, 47.35]. Больше знаков записывать излишне — они не
«верные».
""")
